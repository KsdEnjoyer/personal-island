"""Nine-feature UI acceptance checks, isolated IPC, no personal data."""
import json, os
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
from qa_weather import fixture
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'artifacts/qa'
results=[]
def passed(name): results.append({'test':name,'status':'passed'}); print(name,flush=True)
with sync_playwright() as p:
    executable=sorted((Path(os.environ['LOCALAPPDATA'])/'ms-playwright').glob('chromium_headless_shell-*/**/chrome-headless-shell.exe'))[-1]
    browser=p.chromium.launch(executable_path=str(executable))
    context=browser.new_context(viewport={'width':760,'height':520},timezone_id='Europe/Moscow')
    page=context.new_page();errors=[]
    page.on('pageerror',lambda e: errors.append(str(e)))
    page.add_init_script((ROOT/'scripts/qa-ipc.js').read_text(encoding='utf-8'))
    page.goto('http://127.0.0.1:1420/')
    page.add_style_tag(content='html,body,#app{background:#353b49!important}')
    expect(page.locator('.island-shell')).to_have_attribute('data-shortcut-ready','true')
    page.evaluate('weather=>{qaWeather=weather;qaReveal()}',fixture())
    expect(page.locator('.pill-clock')).to_contain_text('25:00')
    expect(page.locator('.pill-summary')).to_contain_text('4')
    expect(page.locator('.pill-weather')).to_contain_text('-1°')
    expect(page.locator('.pill-playing')).to_have_count(0)
    page.screenshot(path=str(OUT/'v2-overview.png'))
    passed('Manual reveal shows clock, focus timer, remaining tasks and SPb weather without a paused track')
    page.locator('.pill').click()
    page.get_by_label('Закрепить островок').click()
    page.get_by_label('Запустить таймер').click()
    page.evaluate('qaReveal()')
    expect(page.locator('.pill-clock small')).to_have_class('running')
    passed('Running focus timer remains visible in the compact overview')
    page.evaluate("qaMedia={sessions:[{id:'qa.exe',label:'QA Player'}],session_id:'qa.exe',source:'QA Player',title:'Тихий город',artist:'Новый ритм',artwork:'data:image/svg+xml,%3Csvg xmlns=%22http://www.w3.org/2000/svg%22 width=%2264%22 height=%2264%22%3E%3Crect width=%2264%22 height=%2264%22 fill=%22%232b5d58%22/%3E%3Ccircle cx=%2232%22 cy=%2232%22 r=%2218%22 fill=%22%23e6bc78%22/%3E%3C/svg%3E',playing:true,position:12,duration:200,can_toggle:true,can_previous:true,can_next:true};qaReveal('track')")
    expect(page.locator('.track-peek')).to_be_visible()
    expect(page.locator('.peek-title b')).to_have_text('Тихий город')
    expect(page.locator('.equalizer')).to_have_count(0)
    assert page.locator('.pill-artwork').evaluate('el=>el.complete&&el.naturalWidth>0')
    page.get_by_label('Следующий трек',exact=True).first.click()
    page.get_by_label('Предыдущий трек',exact=True).first.click()
    actions=page.evaluate("qaCalls.filter(c=>c.cmd==='media_command').map(c=>c.args.action)")
    assert actions[-2:]==['next','previous'],actions
    page.get_by_label('Показать громкость плеера').click()
    slider=page.get_by_label('Громкость плеера',exact=True)
    expect(slider).to_be_enabled()
    slider.fill('37');slider.dispatch_event('input')
    page.wait_for_timeout(200)
    assert page.evaluate('qaVolume')==.37
    expect(page.locator('.track-peek input[type=range]')).to_be_in_viewport()
    page.screenshot(path=str(OUT/'v2-track-notification.png'))
    passed('Track notification renders artwork and transport/volume controls without separate equalizer bars')
    page.evaluate("qaMedia.playing=false;qaEmit('media-changed',qaMedia)")
    expect(page.locator('.track-peek')).to_have_count(0)
    expect(page.locator('.pill-playing')).to_have_count(0)
    expect(page.locator('.pill-clock')).to_be_visible()
    passed('Pausing playback removes music from the compact island and stops its equalizer')
    page.evaluate("qaReveal('hourly')")
    expect(page.locator('.pill-clock')).to_be_visible()
    expect(page.locator('.pill-summary')).to_contain_text('4')
    expect(page.locator('.pill-weather')).to_contain_text('-1°')
    expect(page.locator('.hourly-peek')).to_have_count(0)
    assert page.locator('.compact-stage').bounding_box()['height']==56
    assert page.locator('.compact-stage').bounding_box()['width']==272
    page.screenshot(path=str(OUT/'v2-hourly.png'))
    passed('Half-hour reveal uses the same default compact island as the keyboard shortcut')
    page.locator('.pill').click()
    page.get_by_label('Закрепить островок').click()
    page.get_by_role('button',name='Погода',exact=True).click()
    expect(page.locator('.weather-hour')).to_have_count(8)
    expect(page.locator('.weather-day')).to_have_count(7)
    expect(page.locator('.weather-panel')).to_have_attribute('data-sky','night')
    page.screenshot(path=str(OUT/'v2-weather-night.png'))
    assert page.locator('.weather-panel').evaluate('el=>el.scrollHeight<=el.clientHeight+1'), page.locator('.weather-panel').evaluate('el=>({height:el.clientHeight,scroll:el.scrollHeight,children:[...el.children].map(c=>[c.className,c.getBoundingClientRect().height])})')
    for code,day,tone in [(0,1,'sunny'),(61,1,'rain'),(71,1,'snow'),(3,1,'cloudy')]:
        page.evaluate('([code,day])=>{qaWeather.data.current.weather_code=code;qaWeather.data.current.is_day=day}',[code,day])
        page.get_by_label('Обновить погоду').click()
        expect(page.locator('.weather-panel')).to_have_attribute('data-sky',tone)
        if tone=='sunny': page.screenshot(path=str(OUT/'v2-weather-sunny.png'))
    page.evaluate("qaWeather.stale=true;qaWeather.error='Нет сети'")
    page.get_by_label('Обновить погоду').click()
    expect(page.locator('.weather-message')).to_contain_text('Данные от')
    page.evaluate("qaWeather={data:null,stale:false,error:'Нет сети'}")
    page.get_by_label('Обновить погоду').click()
    expect(page.locator('.weather-empty')).to_be_visible()
    passed('Weather uses the reference layout, fits eight hours and seven days, labels offline data')
    page.get_by_role('button',name='Календарь',exact=True).click()
    expect(page.locator('.calendar-day')).to_have_count(42)
    expect(page.locator('.compact-month')).to_be_visible()
    expect(page.locator('.calendar-day').last).to_be_in_viewport()
    page.locator('.calendar-day:not(.outside)').nth(9).click()
    expect(page.locator('.calendar-day.selected > span').first).to_have_text('10')
    page.get_by_role('button',name='Следующий месяц').click()
    expect(page.locator('.calendar-day.selected > span').first).to_have_text('1')
    page.get_by_role('button',name='Предыдущий месяц').click()
    page.screenshot(path=str(OUT/'v2-calendar.png'))
    page.locator('.calendar-day.selected').dblclick()
    expect(page.locator('.dashboard')).to_have_attribute('aria-busy','false')
    page.get_by_label('Вид календаря').select_option('month')
    expect(page.locator('.board-month-cell')).to_have_count(42)
    passed('Calendar retains a full month and navigation, with colourful task markers and the reference layout')
    page.get_by_role('button',name='Новое событие',exact=True).click()
    expect(page.get_by_label('Название события')).to_be_visible()
    passed('Calendar planning still opens the task form for the selected date')
    assert not errors,errors
    browser.close()
(OUT/'nine-ui-results.json').write_text(json.dumps(results,ensure_ascii=False,indent=2),encoding='utf-8')
