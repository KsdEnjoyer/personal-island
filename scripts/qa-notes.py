    edit.locator('input[type=checkbox]').first.check()
    expect(edit.locator('li[data-checked=true]')).to_have_count(1)
    assert edit.locator('li[data-checked=true] p').evaluate("e=>getComputedStyle(e).textDecorationLine")=='line-through'
    edit.press('Control+a');page.get_by_role('button',name='Маркированный список').click()
    expect(edit.locator('ul:not([data-type]) > li')).to_have_count(3)
    edit.press('Control+a');page.get_by_role('button',name='Нумерованный список').click()
    expect(edit.locator('ol > li')).to_have_count(3)
    edit.press('Control+a');page.get_by_role('button',name='Чек-лист',exact=True).click()
    edit.locator('input[type=checkbox]').first.check()
    passed('All three list types convert correctly; checkboxes visibly complete and strike their text')
    page.get_by_role('tab',name='Идеи',exact=True).click()
    expect(title).to_have_value('')
    title.fill('Идея островка');edit.fill('Музыкальная погода')
    page.get_by_role('tab',name='Покупки',exact=True).click()
    expect(edit.locator('input[type=checkbox]')).to_have_count(1)
    title.fill('Продукты');edit.locator('p').fill('Молоко')
    page.get_by_role('tab',name='Заметки',exact=True).click()
    expect(title).to_have_value('Выпуск в пятницу')
    expect(edit.locator('input[type=checkbox]')).to_have_count(3)
    expect(edit.locator('li[data-checked=true]')).to_have_count(1)
    assert len(page.evaluate('qaNotes'))==3
    page.get_by_role('button',name='Новая запись',exact=True).click()
    title.fill('Вторая заметка');edit.fill('Не потерять текст')
    page.get_by_role('button',name='Сегодня',exact=True).click()
    expect(page.get_by_role('button',name='Сегодня',exact=True)).to_have_attribute('aria-current','page')
    page.get_by_role('button',name='Заметки',exact=True).click()
    expect(title).to_have_value('Вторая заметка')
    page.get_by_label('Открыть запись').select_option(label='Выпуск в пятницу')
    expect(title).to_have_value('Выпуск в пятницу')
    passed('Notes, ideas and shopping remain separate; multiple notes and immediate tab switches retain edits')
    page.get_by_role('button',name='Копировать заметку').click()
    expect(page.get_by_role('status')).to_contain_text('Заметка скопирована')
    copied=page.evaluate('navigator.clipboard.readText()')
    assert 'Выпуск в пятницу' in copied and 'Проверить обновление' in copied
    assert page.evaluate('navigator.clipboard.read().then(items=>items[0].types.includes("text/html"))')
    passed('Copy exports readable text and rich HTML to the browser clipboard')
    page.get_by_role('button',name='Напомнить о заметке').click()
    page.get_by_label('Текст напоминания из заметки').fill('Позвонить Ане')
    page.get_by_role('button',name='Создать напоминание',exact=True).click()
    expect(page.get_by_role('status')).to_contain_text('Напоминание добавлено')
    task=page.evaluate('qaTasks.at(-1)');assert task['due_at']==task['reminder_at'] and task['title']=='Позвонить Ане'
    quick=page.get_by_role('textbox',name='Быстрое напоминание',exact=True);quick.fill('Позвонить маме завтра в 9');quick.press('Enter')
    expect(quick).to_have_value('')
    task=page.evaluate('qaTasks.at(-1)');assert task['title']=='Позвонить маме' and task['due_at']==task['reminder_at']
    quick.fill('Купить хлеб');quick.press('Enter')
    expect(page.get_by_label('Время быстрого напоминания')).to_be_visible()
