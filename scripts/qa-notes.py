    assert page.locator('.timer-value').inner_text().startswith(('26:','27:'))
    page.get_by_role('button',name='Приостановить таймер').click()
    remaining=page.locator('.timer-value').inner_text();page.wait_for_timeout(1100);expect(page.locator('.timer-value')).to_have_text(remaining)
    page.get_by_role('button',name='Сбросить таймер').click();expect(page.locator('.timer-value')).to_have_text('25:00')
    passed('Focus timer starts, pauses, adds one minute while running/paused and resets')
    page.evaluate("qaFail='save_note'");title.fill('Несохранённая правка')
    page.get_by_role('button',name='Сегодня',exact=True).click()
    expect(page.locator('.note-error')).to_contain_text('QA simulated failure')
    expect(title).to_have_value('Несохранённая правка')
    page.evaluate('qaFail=null');page.get_by_role('button',name='Повторить сохранение').click()
    expect(page.locator('.note-error')).to_have_count(0)
    page.get_by_role('button',name='Удалить заметку',exact=True).click()
    page.get_by_role('button',name='Отмена',exact=True).click();expect(title).to_have_value('Несохранённая правка')
    page.get_by_role('button',name='Удалить заметку',exact=True).click()
    page.get_by_role('button',name='Удалить запись',exact=True).click()
    expect(title).to_have_value('Вторая заметка')
    assert len(page.evaluate('qaNotes'))==3
    passed('Save failure preserves the draft and blocks navigation; retry and explicit delete confirmation work')
    page.evaluate('qaNotesDelay=650')
    title.fill('Медленное сохранение');page.wait_for_timeout(500)
    edit.fill('Последняя правка во время сохранения')
    page.get_by_role('tab',name='Идеи',exact=True).click()
    page.get_by_role('tab',name='Заметки',exact=True).click()
    expect(title).to_have_value('Медленное сохранение');expect(edit).to_contain_text('Последняя правка во время сохранения')
    page.evaluate('qaNotesDelay=0')
    passed('Edits made during an in-flight save survive a category switch')
    page.evaluate("qaNotes.find(n=>n.title==='Медленное сохранение').revision++")
    title.fill('Копия при конфликте')
    page.get_by_role('button',name='Сегодня',exact=True).click()
    expect(page.locator('.note-error')).to_contain_text('Revision conflict')
    page.get_by_role('button',name='Сохранить копию',exact=True).click()
